const assert = require('node:assert/strict');
const { snapshot, outcome, CAMPAIGN_SCENES } = require('../guilda-expedition-view.js');
let checks = 0;
const active = { start: 1000, dur: 100000, m: { name: 'Patrulha', req: 18 } };
const at = (pct, extra = {}) => snapshot({ ...active, ...extra }, 1000 + pct * 1000);
assert.equal(at(0).phase, 'departure'); checks++;
assert.equal(at(17.9).phase, 'departure'); checks++;
assert.equal(at(18).phase, 'exploration'); checks++;
assert.equal(at(62).phase, 'objective'); checks++;
assert.equal(at(88).phase, 'return'); checks++;
assert.equal(at(140).progress, 100); checks++;
assert.equal(at(-10).progress, 0); checks++;
assert.equal(at(40).isCampaign, false); checks++;
assert.equal(at(40).scene.atmosphere, 'road'); checks++;
const campaign = at(40, { m: { name: 'Capítulo', campaignStep: 3 } });
assert.equal(campaign.isCampaign, true); checks++;
assert.equal(campaign.scene.title, 'Rei Demônio'); checks++;
assert.equal(campaign.atmosphere, 'citadel'); checks++;
assert.equal(campaign.encounter, 'Rei Demônio'); checks++;
assert.equal(at(62, { m: { name: 'Capítulo', campaignStep: 3 } }).isConfrontation, true); checks++;
assert.equal(campaign.beat, 'O último inimigo se revela'); checks++;
assert.equal(CAMPAIGN_SCENES.length, 4); checks++;
const win = outcome({ mission: { campaignStep: 3, name: 'Rei Demônio' }, campaignStageBefore: 3, campaignStageAfter: 4, goldBefore: 100, goldAfter: 200, repBefore: 10, repAfter: 20, now: 5000 });
assert.equal(win.success, true); checks++;
assert.equal(win.finalVictory, true); checks++;
assert.equal(win.title, 'A Guilda salvou o reino!'); checks++;
const loss = outcome({ mission: { name: 'Patrulha' }, campaignStageBefore: 0, campaignStageAfter: 0, goldBefore: 100, goldAfter: 100, repBefore: 0, repAfter: 0, now: 6000 });
assert.equal(loss.success, false); checks++;
assert.equal(loss.finalVictory, false); checks++;
assert.equal(outcome({ mission: { campaignStep: 0 }, campaignStageBefore: 0, campaignStageAfter: 1, goldBefore: 100, goldAfter: 100, repBefore: 0, repAfter: 0 }).isCampaign, true); checks++;
assert.throws(() => snapshot(null, 1000), TypeError); checks++;
assert.throws(() => snapshot({ start: 1, dur: 0, m: {} }, 1000), TypeError); checks++;
console.log('Expedition view: ' + checks + ' checks passed.');
